"""The retrieval harness — scored without an index, because there isn't one yet.

The knowledge base has never been ingested (0 objects, 0 ingestion jobs), so
the harness cannot produce a baseline today. What it can do is be *correct*
before the first ingest, which is the whole point of building it now: the
moment the human runs the first ingest, the score is one command away, and a
baseline taken after the corpus has been reshaped is not a baseline.

So every case below runs against a fake agent runtime. The arithmetic, the
key mapping, the stamp check and the refusal to score an unratified answer key
are all exercised; only the numbers are absent.
"""

from typing import Any

import pytest
from docpipe_core.kb_eval import (
    EvalReport,
    QuestionSet,
    UnratifiedAnswerKey,
    chunk_key_of,
    load_question_set,
    score_question_set,
    stamp_is_complete,
)
from docpipe_core.retrieval import KnowledgeBaseClient, RetrievedPassage

BUCKET = "s3://docpipe-dev-kb-source-733866507398/corpus/"

PAIN_05 = "anatomy/12-pain-science--05-central-sensitization-the-volume-knob.md"
PAIN_06 = "anatomy/12-pain-science--06-fear-avoidance-how-pain-becomes-chronic.md"
PATELLA = "graph/body-graph-structure--patella.md"
GLENOHUMERAL = "graph/body-graph-joint--glenohumeral.md"
INDEX = "graph/body-graph-index.md"

PROVENANCE = "<!-- health.studio knowledge base · generated by build-kb.ts · do not edit -->"
SCALE_LINE = (
    "> **Evidence scale** · ★★★ strong (systematic review / RCT) · ★★☆ moderate ·"
    " ★☆☆ emerging · ☆☆☆ conceptual. Graded on the weakest link in the claim."
)
USE_LINE = (
    "> **Use** · Educational. Not a diagnosis and not medical advice."
    " Vocabulary defined in `docs/anatomy/evidence-honesty.md`."
)

# A real stamped chunk, trimmed. Everything the header must carry is here.
STAMPED = f"""{PROVENANCE}

# Pain Science
## Central Sensitization: The "Volume Knob"

> **Source** · `docs/anatomy/12-pain-science.md` · part 5/15
{SCALE_LINE}
{USE_LINE}

---

Central sensitization is a real and measurable phenomenon ★★★ [VERIFIED].
"""

# What a splitter hands back as fragment 2 of the same chunk. Stars survive;
# the scale that gives them meaning does not.
SPLIT_TAIL = """## A second section, far below the header

Fascia may transmit force across compartments ★☆☆ [SYNTHESIS].
"""

# A legitimately unrated chunk: no ★ anywhere, so the adaptive stamper writes
# no scale. Demanding one here would fail 97 honest chunks.
UNRATED = f"""{PROVENANCE}

# Myofascial Chains (Anatomy Trains)
## Sources

> **Source** · `docs/anatomy/01-myofascial-chains.md` · part 9/9
> **Unrated** · This passage carries no evidence rating and no citation of its own.
{USE_LINE}

---

- Myers TW. Anatomy Trains. 4th ed. Elsevier; 2020.
"""


class FakeAgentRuntime:
    """Returns a canned result list per query text."""

    def __init__(self, by_query: dict[str, list[dict[str, Any]]]) -> None:
        self.by_query = by_query
        self.calls: list[dict[str, Any]] = []

    def retrieve(self, **kwargs: Any) -> dict[str, Any]:
        self.calls.append(kwargs)
        query = kwargs["retrievalQuery"]["text"]
        return {"retrievalResults": self.by_query.get(query, [])}


def result(key: str, text: str = STAMPED, score: float = 0.9) -> dict[str, Any]:
    return {
        "content": {"text": text},
        "score": score,
        "metadata": {"x-amz-bedrock-kb-source-uri": BUCKET + key},
    }


def question_set(**overrides: Any) -> QuestionSet:
    payload: dict[str, Any] = {
        "version": 1,
        "authored": "2026-08-14",
        "ratified": "2026-08-20",
        "ratified_by": "human",
        "questions": [
            {
                "id": "prose-01",
                "stratum": "prose",
                "class": "direct",
                "question": "why does pain persist",
                "expected": [PAIN_05],
                "why": "",
            },
            {
                "id": "struct-01",
                "stratum": "graph-structure",
                "class": "structure-only",
                "question": "what is the patella",
                "expected": [PATELLA],
                "why": "",
            },
            {
                "id": "gap-02",
                "stratum": "not-covered",
                "class": "not-covered",
                "question": "tell me about the knee joint",
                "expected": [INDEX],
                "must_not_return": [GLENOHUMERAL],
                "why": "",
            },
        ],
    }
    payload.update(overrides)
    return QuestionSet.model_validate(payload)


# ── The stamp check ────────────────────────────────────────────────────────


def test_a_whole_stamped_chunk_is_complete() -> None:
    assert stamp_is_complete(STAMPED)


def test_a_split_fragment_is_not_complete() -> None:
    # This is the assertion the metric exists for. The fragment still carries
    # ★☆☆ and [SYNTHESIS]; it carries no scale and no "not a diagnosis" line,
    # so the model receives bare stars that read as authority.
    assert not stamp_is_complete(SPLIT_TAIL)


def test_an_unrated_chunk_needs_no_scale() -> None:
    assert stamp_is_complete(UNRATED)


def test_stars_without_their_scale_fail_even_with_a_header() -> None:
    mutilated = STAMPED.replace(SCALE_LINE + "\n", "")
    assert "★" in mutilated
    assert not stamp_is_complete(mutilated)


def test_a_missing_disclaimer_fails() -> None:
    assert not stamp_is_complete(STAMPED.replace(USE_LINE, "> **Use** ·"))


# ── Key mapping ────────────────────────────────────────────────────────────


def test_chunk_key_is_the_path_under_the_prefix() -> None:
    passage = RetrievedPassage(text="", source=BUCKET + "anatomy/12-pain-science--01-overview.md")
    assert chunk_key_of(passage) == "anatomy/12-pain-science--01-overview.md"


def test_a_passage_with_no_source_has_no_key() -> None:
    assert chunk_key_of(RetrievedPassage(text="orphan")) is None


def test_a_uri_outside_the_prefix_has_no_key() -> None:
    passage = RetrievedPassage(text="", source="s3://other-bucket/elsewhere/doc.md")
    assert chunk_key_of(passage) is None


def test_source_path_is_not_used_as_a_fallback_key() -> None:
    # sourcePath names the authoring document, one level above the chunk.
    # Grading on it would silently score documents instead of chunks.
    passage = RetrievedPassage(text="", source=None, source_path="docs/anatomy/12-pain-science.md")
    assert chunk_key_of(passage) is None


# ── The score ──────────────────────────────────────────────────────────────


def scored(by_query: dict[str, list[dict[str, Any]]], **kwargs: Any) -> EvalReport:
    fake = FakeAgentRuntime(by_query)
    client = KnowledgeBaseClient("kb-123", agent_runtime_client=fake)
    return score_question_set(client, question_set(), **kwargs)


def test_a_perfect_run_scores_one_everywhere() -> None:
    report = scored(
        {
            "why does pain persist": [result(PAIN_05)],
            "what is the patella": [result(PATELLA)],
            "tell me about the knee joint": [result(INDEX)],
        }
    )
    assert report.overall.recall_at_k == 1.0
    assert report.overall.mrr == 1.0
    assert report.overall.stamp_integrity == 1.0
    assert report.forbidden_violations == []


def test_rank_three_costs_mrr_but_not_recall() -> None:
    report = scored(
        {
            "why does pain persist": [
                result("anatomy/00-index--01-overview.md"),
                result("anatomy/12-pain-science--01-overview.md"),
                result(PAIN_05),
            ],
        }
    )
    prose = next(s for s in report.by_stratum if s.stratum == "prose")
    assert prose.recall_at_k == 1.0
    assert prose.mrr == round(1 / 3, 4)
    assert next(r for r in report.results if r.id == "prose-01").rank == 3


def test_a_miss_is_recorded_by_id_not_just_counted() -> None:
    report = scored({"what is the patella": [result(GLENOHUMERAL)]})
    structure = next(s for s in report.by_stratum if s.stratum == "graph-structure")
    assert structure.recall_at_k == 0.0
    assert structure.mrr == 0.0
    assert structure.misses == ["struct-01"]


def test_strata_are_scored_apart_so_one_cannot_mask_the_other() -> None:
    # The failure mode the per-stratum rule exists for: prose perfect, the
    # graph half at zero. A single average would call this 0.33 and move on.
    report = scored(
        {
            "why does pain persist": [result(PAIN_05)],
            "what is the patella": [result("anatomy/05-muscle-anatomy-database--02-upper-body.md")],
            "tell me about the knee joint": [result("anatomy/00-index--01-overview.md")],
        }
    )
    scores = {s.stratum: s.recall_at_k for s in report.by_stratum}
    assert scores["prose"] == 1.0
    assert scores["graph-structure"] == 0.0
    assert report.overall.recall_at_k == round(1 / 3, 4)


def test_a_not_covered_question_abstains_when_the_magnet_stays_out() -> None:
    report = scored({"tell me about the knee joint": [result(INDEX)]})
    gap = next(s for s in report.by_stratum if s.stratum == "not-covered")
    assert gap.abstention == 1.0
    assert report.forbidden_violations == []


def test_confabulating_the_nearest_neighbour_is_reported_at_the_top_level() -> None:
    # glenohumeral is the only joint of 28 modelled. Returning it for a knee
    # question is the confabulation this stratum exists to catch, and it is
    # hoisted out of the per-question detail because it is a safety result.
    report = scored({"tell me about the knee joint": [result(GLENOHUMERAL)]})
    gap = next(s for s in report.by_stratum if s.stratum == "not-covered")
    assert gap.abstention == 0.0
    assert report.forbidden_violations == ["gap-02"]


def test_abstention_is_none_for_strata_that_have_a_right_answer() -> None:
    report = scored({"why does pain persist": [result(PAIN_05)]})
    prose = next(s for s in report.by_stratum if s.stratum == "prose")
    assert prose.abstention is None


def test_stamp_integrity_counts_passages_not_questions() -> None:
    report = scored(
        {
            "why does pain persist": [
                result(PAIN_05),
                result(PAIN_06, text=SPLIT_TAIL),
            ],
        }
    )
    prose = next(s for s in report.by_stratum if s.stratum == "prose")
    assert prose.passages == 2
    assert prose.stamped == 1
    assert prose.stamp_integrity == 0.5


def test_no_passages_is_zero_integrity_not_perfect_integrity() -> None:
    report = scored({})
    assert report.overall.passages == 0
    assert report.overall.stamp_integrity == 0.0
    assert report.overall.recall_at_k == 0.0


def test_k_and_the_evidence_filter_reach_the_shipped_client() -> None:
    """What this owns is PASS-THROUGH: the harness's k and floor reach the real
    client rather than a local reimplementation of it.

    It deliberately does not assert the filter's shape. It used to, and the
    safety exemption (`retrieval.py` — the floor is OR'd with `safetyCritical`)
    broke it here for a reason that has nothing to do with this harness. The
    shape is `test_retrieval.py`'s to own; this asserts the floor arrives.
    """
    fake = FakeAgentRuntime({})
    client = KnowledgeBaseClient("kb-123", agent_runtime_client=fake)
    score_question_set(client, question_set(), k=7, min_evidence=2)

    search = fake.calls[0]["retrievalConfiguration"]["vectorSearchConfiguration"]
    assert search["numberOfResults"] == 7
    sent = str(search["filter"])
    assert "maxEvidence" in sent and "2" in sent
    assert len(fake.calls) == 3


def test_the_report_carries_its_own_n_and_k() -> None:
    report = scored({}, k=5)
    assert (report.n, report.k, report.knowledge_base_id) == (3, 5, "kb-123")
    assert report.question_set["ratified"] == "2026-08-20"


def test_rerank_reaches_the_client_and_the_report_records_it() -> None:
    """Same pass-through contract as k and the floor — and the report must say
    which experiment it was, or a reranked score gets compared to the raw
    baseline as if they measured the same thing."""
    fake = FakeAgentRuntime({})
    client = KnowledgeBaseClient("kb-123", agent_runtime_client=fake)
    report = score_question_set(client, question_set(), rerank=True, rerank_pool=20)

    search = fake.calls[0]["retrievalConfiguration"]["vectorSearchConfiguration"]
    assert search["numberOfResults"] == 20
    assert "rerankingConfiguration" in search
    assert (report.rerank, report.rerank_pool) == (True, 20)


def test_a_raw_report_says_so() -> None:
    report = scored({})
    assert (report.rerank, report.rerank_pool) == (False, None)


# ── The human gate, enforced ───────────────────────────────────────────────


def test_an_unratified_answer_key_refuses_to_be_scored() -> None:
    fake = FakeAgentRuntime({})
    client = KnowledgeBaseClient("kb-123", agent_runtime_client=fake)
    with pytest.raises(UnratifiedAnswerKey):
        score_question_set(client, question_set(ratified=None, ratified_by=None))
    assert fake.calls == [], "it must refuse before spending a single retrieval"


def test_a_dry_run_is_allowed_but_has_to_be_asked_for() -> None:
    fake = FakeAgentRuntime({})
    client = KnowledgeBaseClient("kb-123", agent_runtime_client=fake)
    report = score_question_set(
        client, question_set(ratified=None, ratified_by=None), require_ratified=False
    )
    assert report.question_set["ratified"] is None


# ── The real question set, as shipped by the producer ──────────────────────


def test_the_shipped_question_set_loads_and_is_not_yet_ratified(tmp_path: Any) -> None:
    # health.studio owns the file; docpipe owns the harness. Rather than
    # depending on a sibling checkout, this asserts the shape the harness
    # requires of it — the same shape questions.test.ts asserts over there.
    path = tmp_path / "questions.json"
    path.write_text(question_set(ratified=None, ratified_by=None).model_dump_json(by_alias=True))
    loaded = load_question_set(path)
    assert not loaded.is_ratified
    assert loaded.questions[0].question_class == "direct"
